/**
 * The vertical funnel, exported.
 *
 * Parses the *prospecting* filter set, because that is what its screen parses —
 * one vertical at a time, one person filter called `user`. Both halves calling
 * `pickReportFilters` is what keeps the file and the page in step.
 */
async function buildFunnelTable(
  viewer: CurrentUser,
  params: Params,
): Promise<ReportTable> {
  const filters = pickReportFilters(params)
  const range = resolveRange(filters)
  const people = await resolvePeople(viewer, filters)

  const verticals = await prisma.salesVertical.findMany({
    where: { isActive: true },
    select: {
      id: true,
      name: true,
      metrics: {
        where: { isActive: true },
        select: { id: true, key: true, label: true, isLeadTrigger: true },
        orderBy: { sortOrder: 'asc' },
      },
      stages: {
        where: { isActive: true },
        select: { id: true, code: true, name: true, isWon: true, isLost: true },
        orderBy: { sortOrder: 'asc' },
      },
    },
    orderBy: { sortOrder: 'asc' },
  })

  const vertical =
    verticals.find((row) => row.id === filters.vertical) ?? verticals[0]

  if (!vertical) {
    return {
      title: 'Vertical funnel',
      columns: [{ header: 'Step' }],
      rows: [],
      meta: [['Period', `${formatCounterDate(range.from)} to ${formatCounterDate(range.to)}`]],
    }
  }

  const [counters, leadsByVertical, reached] = await Promise.all([
    counterTotals(range, people, vertical.id),
    leadsCreatedByVertical(range, people, vertical.id),
    reachedByStage(range, people, vertical.id),
  ])

  const funnel = buildFunnel(
    vertical,
    counters,
    leadsByVertical.get(vertical.id) ?? 0,
    reached,
  )

  const lostStage = vertical.stages.find((stage) => stage.isLost)

  return {
    title: `${vertical.name} funnel`,
    subtitle:
      'Counters are dated by the day the work was logged; stage counts by the day the transition happened, and each is leads that ever passed through that stage rather than leads sitting there now.',
    meta: [
      [
        'Period',
        `${formatCounterDate(range.from)} to ${formatCounterDate(range.to)}`,
      ],
      ['Vertical', vertical.name],
      ['Person', people.only ? 'Filtered' : 'Everyone in scope'],
    ],
    columns: [
      { header: 'Half', width: 16 },
      { header: 'Step', width: 30 },
      { header: 'Count', format: 'number' },
      { header: 'Conversion %', format: 'percent', width: 14 },
      { header: 'Of', width: 26 },
    ],
    rows: [
      ...funnel.above.map((step) => [
        'Above the line',
        step.label,
        step.value,
        step.conversion,
        step.conversionOf,
      ]),
      ...(funnel.bridge
        ? [
            [
              'Bridge',
              funnel.bridge.label,
              funnel.bridge.value,
              funnel.bridge.conversion,
              funnel.bridge.conversionOf,
            ],
          ]
        : []),
      ...funnel.below.map((step) => [
        'Below the line',
        step.label,
        step.value,
        step.conversion,
        step.conversionOf,
      ]),
      ...(lostStage
        ? [
            [
              'Outcome',
              lostStage.name,
              reached.get(lostStage.id) ?? 0,
              null,
              'Reported beside the funnel, not inside it',
            ],
          ]
        : []),
    ],
  }
}

/** The staffing report's three levels, flattened into one metric table. */
async function buildStaffingTable(
  viewer: CurrentUser,
  params: Params,
): Promise<ReportTable> {
  const filters = pickReportFilters(params)
  const range = resolveRange(filters)
  const people = await resolvePeople(viewer, filters)

  const [requirementStages, candidateStages] = await Promise.all([
    prisma.requirementStage.findMany({
      where: { isActive: true },
      select: { id: true, code: true, name: true },
      orderBy: { sortOrder: 'asc' },
    }),
    prisma.candidateStage.findMany({
      where: { isActive: true },
      select: { id: true, code: true, name: true },
      orderBy: { sortOrder: 'asc' },
    }),
  ])

  const profileSharedStageId = byCode(
    candidateStages,
    CANDIDATE_STAGE_CODES.profileShared,
  )

  const [totals, requirementReached, subReached, sourced, outcomes, activity] =
    await Promise.all([
      requirementTotals(range, people),
      requirementReachedByStage(range, people),
      subReachedByStage(range, people),
      candidatesSourced(range, people),
      interviewAndPlacementTotals(range, people),
      requirementsWithActivity(range, people, profileSharedStageId),
    ])

  const qualifiedId = byCode(requirementStages, REQUIREMENT_STAGE_CODES.qualified)
  const qualified = qualifiedId ? (requirementReached.get(qualifiedId) ?? 0) : 0

  const shared = reachedFor(
    subReached,
    candidateStages,
    CANDIDATE_STAGE_CODES.profileShared,
  )
  const shortlisted = reachedFor(
    subReached,
    candidateStages,
    CANDIDATE_STAGE_CODES.shortlisted,
  )
  const interviewScheduled = reachedFor(
    subReached,
    candidateStages,
    CANDIDATE_STAGE_CODES.interviewScheduled,
  )
  const interviewCompleted = reachedFor(
    subReached,
    candidateStages,
    CANDIDATE_STAGE_CODES.interviewCompleted,
  )
  const selected = reachedFor(
    subReached,
    candidateStages,
    CANDIDATE_STAGE_CODES.selected,
  )

  // Metric, unit, value — a shape docs/02 §4.7 is already written in, and the one
  // that survives being read in a spreadsheet without the units being guessed.
  const rows: ReportTable['rows'] = [
    ['Requirements received', 'requirements', totals.received, null],
    ['Qualified requirements', 'requirements', qualified, rate(qualified, totals.received)],
    ['Openings', 'positions', totals.openings, null],
    ['Positions filled', 'positions', totals.positionsFilled, rate(totals.positionsFilled, totals.openings)],
    ['Candidates sourced', 'people', sourced, null],
    ['Profiles shared', 'submissions', shared, null],
    ['Profiles shortlisted', 'submissions', shortlisted, rate(shortlisted, shared)],
    ['Interviews scheduled', 'submissions', interviewScheduled, rate(interviewScheduled, shortlisted)],
    ['Interviews held', 'rounds', outcomes.interviews, null],
    ['Selections', 'submissions', selected, rate(selected, interviewCompleted)],
    ['Placements', 'placements', outcomes.placements, rate(outcomes.placements, selected)],
    ['Requirements with a profile shared', 'requirements', activity.withProfileShared, rate(activity.withProfileShared, totals.received)],
    ['Requirements with a placement', 'requirements', activity.withPlacement, rate(activity.withPlacement, totals.received)],
    // The conversion belongs on the filled row: it is `filled ÷ (filled + lost)`,
    // the requirement conversion of docs/02 §5. Sitting on the lost row it read
    // as a loss rate and said the opposite of what it computed.
    [
      'Requirements filled',
      'requirements',
      totals.filled,
      rate(totals.filled, totals.filled + totals.lost),
    ],
    ['Requirements lost', 'requirements', totals.lost, null],
    ['Requirements cancelled', 'requirements', totals.cancelled, null],
    ['Requirements still live', 'requirements', totals.open + totals.onHold, null],
  ]

  return {
    title: 'Staffing',
    subtitle:
      'Requirements are dated by the day they were raised, stage figures by the day the transition happened, and placements by the day the person joined. Requirement counts and submission counts are different units — the Unit column says which.',
    meta: [
      [
        'Period',
        `${formatCounterDate(range.from)} to ${formatCounterDate(range.to)}`,
      ],
      ['Person', people.only ? 'Filtered' : 'Everyone in scope'],
    ],
    columns: [
      { header: 'Metric', width: 34 },
      { header: 'Unit', width: 14 },
      { header: 'Value', format: 'number' },
      { header: 'Conversion %', format: 'percent', width: 14 },
    ],
    rows,
  }
}

