/**
 * The eleven reports, as data.
 *
 * Each entry says what a report is called, what permission it sits behind, and
 * how to turn a request's query string into a `ReportTable`. The export route is
 * then one route handler for every report and every format, and — the part that
 * matters — each `build` calls **the same loader the screen calls, with the same
 * parameters**, so the file cannot drift from the page. Phase 2's lead export
 * established that rule; this is it applied eleven times without eleven routes.
 *
 * The two Phase 3/4 reports are here too. Their screens parse the narrower
 * prospecting filter set (`user` rather than `bde`/`bdm`), so their builders
 * parse it as well rather than pretending everything shares one vocabulary — the
 * export link on those pages carries their own query string, and both halves
 * agree because both call `pickReportFilters`.
 */

type Params = Record<string, string | string[] | undefined>

export type ReportDefinition = {
  key: string
  title: string
  permission: Permission
  /** File name stem: `lead-source-2026-08-17.xlsx`. */
  basename: string
  build: (viewer: CurrentUser, params: Params) => Promise<ReportTable>
}

const number = (value: number) => value

/**
 * The filter set as label/value pairs, for the export's own header block.
 *
 * A file outlives the URL that made it. Without the period and the filters
 * printed on it, "Won revenue 412,000" in an email six weeks later is a number
 * with no question attached — so every export carries them, resolved to names
 * rather than left as ids nobody can read.
 */
async function analyticsMeta(
  scope: AnalyticsScope,
): Promise<Array<[string, string]>> {
  const [vertical, source, bde, bdm, team] = await Promise.all([
    scope.verticalId
      ? prisma.salesVertical.findUnique({
          where: { id: scope.verticalId },
          select: { name: true },
        })
      : null,
    scope.sourceId
      ? prisma.leadSource.findUnique({
          where: { id: scope.sourceId },
          select: { name: true },
        })
      : null,
    scope.bde
      ? prisma.user.findUnique({
          where: { id: scope.bde },
          select: { name: true },
        })
      : null,
    scope.bdm
      ? prisma.user.findUnique({
          where: { id: scope.bdm },
          select: { name: true },
        })
      : null,
    scope.teamId
      ? prisma.team.findUnique({
          where: { id: scope.teamId },
          select: { name: true },
        })
      : null,
  ])

  const meta: Array<[string, string]> = [
    [
      'Period',
      `${formatCounterDate(scope.range.from)} to ${formatCounterDate(scope.range.to)}`,
    ],
    ['Vertical', vertical?.name ?? 'All verticals'],
    ['Source', source?.name ?? 'All sources'],
    ['Generated by', bde?.name ?? 'Anyone'],
    ['Assigned to', bdm?.name ?? 'Anyone'],
    ['Team', team?.name ?? 'All teams'],
    [
      'Status',
      scope.status ? LEAD_STATUS_LABELS[scope.status as LeadStatus] : 'Any',
    ],
    [
      'Priority',
      scope.priority
        ? PRIORITY_LABELS[scope.priority as Priority]
        : 'Any',
    ],
  ]

  return meta
}

