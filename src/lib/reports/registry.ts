async function buildBde(
  viewer: CurrentUser,
  params: Params,
): Promise<ReportTable> {
  const scope = await resolveAnalytics(viewer, params)
  const [rows, counters, meta] = await Promise.all([
    groupedPerformance(scope, 'generatedById', ['WON']),
    counterTotalsByPerson(scope),
    analyticsMeta(scope),
  ])

  const keys = new Set([...rows.map((row) => row.key), ...counters.keys()])
  const labels = await groupLabels('generatedById', [...keys])

  const people = [...keys]
    .map((key) => {
      const row = rows.find((candidate) => candidate.key === key)
      const logged = counters.get(key) ?? 0
      const leads = row?.counts.total ?? 0

      return {
        name: labels.get(key) ?? 'Former user',
        logged,
        leads,
        open: row?.counts.open ?? 0,
        won: row?.reached.WON ?? 0,
        lost: row?.counts.lost ?? 0,
        conversion: row?.conversion ?? null,
        pipeline: row?.pipeline ?? 0,
        wonRevenue: row?.wonRevenue ?? 0,
        bridge: logged > 0 ? rate(leads, logged) : null,
      }
    })
    .sort((a, b) => b.leads - a.leads || b.logged - a.logged)

  return {
    title: 'BDE lead generation',
    subtitle:
      'Grouped by whoever generated the lead, never by assignee. Counters are dated by the day the work was logged and leads by the day they were created, so the bridge percentage is an approximation across the month boundary.',
    meta,
    columns: [
      { header: 'Person', width: 24 },
      { header: 'Counters logged', format: 'number', width: 16 },
      { header: 'Leads generated', format: 'number', width: 16 },
      { header: 'Bridge %', format: 'percent' },
      { header: 'Open', format: 'number' },
      { header: 'Won', format: 'number' },
      { header: 'Lost', format: 'number' },
      { header: 'Conversion %', format: 'percent' },
      { header: 'Pipeline', format: 'money', width: 16 },
      { header: 'Won revenue', format: 'money', width: 16 },
    ],
    rows: people.map((person) => [
      person.name,
      person.logged === 0 ? null : person.logged,
      person.leads,
      person.bridge,
      person.open,
      person.won,
      person.lost,
      person.conversion,
      person.pipeline,
      person.wonRevenue,
    ]),
    footer: [
      'Everyone in scope',
      people.reduce((sum, person) => sum + person.logged, 0),
      people.reduce((sum, person) => sum + person.leads, 0),
      null,
      people.reduce((sum, person) => sum + person.open, 0),
      people.reduce((sum, person) => sum + person.won, 0),
      people.reduce((sum, person) => sum + person.lost, 0),
      null,
      people.reduce((sum, person) => sum + person.pipeline, 0),
      people.reduce((sum, person) => sum + person.wonRevenue, 0),
    ],
  }
}

