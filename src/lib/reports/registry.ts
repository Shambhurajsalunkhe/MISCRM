async function buildVertical(
  viewer: CurrentUser,
  params: Params,
): Promise<ReportTable> {
  const scope = await resolveAnalytics(viewer, params)

  const [rows, verticals, revenue, meta] = await Promise.all([
    groupedPerformance(scope, 'verticalId', ['WON']),
    verticalsWithStages(),
    revenueTotals(scope),
    analyticsMeta(scope),
  ])

  const counters = await counterTotals(
    scope.range,
    peopleScopeOf(scope),
    scope.verticalId,
  )

  const byKey = new Map(rows.map((row) => [row.key, row]))
  const listed = verticals.filter(
    (vertical) => scope.verticalId === null || vertical.id === scope.verticalId,
  )

  return {
    title: 'Vertical performance',
    subtitle:
      'Leads are counted by creation date; Won by the date the lead reached its winning stage. Pipeline and Pending are as at today. The input column is not totalled — pitches, calls and campaigns are different units.',
    meta,
    columns: [
      { header: 'Vertical', width: 22 },
      { header: 'Input metric', width: 22 },
      { header: 'Input', format: 'number' },
      { header: 'Leads', format: 'number' },
      { header: 'Bridge %', format: 'percent' },
      { header: 'Open', format: 'number' },
      { header: 'Won', format: 'number' },
      { header: 'Lost', format: 'number' },
      { header: 'Won ÷ leads %', format: 'percent' },
      { header: 'Pipeline', format: 'money', width: 16 },
      { header: 'Won revenue', format: 'money', width: 16 },
      { header: 'Collected', format: 'money', width: 16 },
      { header: 'Pending', format: 'money', width: 16 },
    ],
    rows: listed.map((vertical) => {
      const row = byKey.get(vertical.id)
      const money = revenue.byVertical.get(vertical.id)
      const trigger = leadTriggerMetric(vertical.metrics)
      const input = trigger.metric
        ? (counters.get(trigger.metric.id) ?? 0)
        : null
      const leads = row?.counts.total ?? 0
      const won = row?.reached.WON ?? 0

      return [
        vertical.name,
        leadTriggerLabel(trigger),
        input,
        number(leads),
        input === null ? null : rate(leads, input),
        row?.counts.open ?? 0,
        won,
        row?.counts.lost ?? 0,
        rate(won, leads),
        row?.pipeline ?? 0,
        row?.wonRevenue ?? 0,
        money?.collected ?? 0,
        money?.pending ?? 0,
      ]
    }),
  }
}

